import { pierreDark, pierreLight, toCSS } from '@pierre/highlights/themes';

/** The prefix the highlighter asks @pierre/highlights to name categories with. */
export const CODE_VAR_PREFIX = '--code-';

/** Checked in beside this module, imported only by posts that have a code block. */
export const CODE_THEME_CSS_PATH = '#lib/markdown/code-theme.css';

/** Inherited from the `<pre>`, so a token in it needs no class. */
export const FOREGROUND = `var(${CODE_VAR_PREFIX}foreground)`;

/**
 * @param {import('@pierre/highlights').Theme} theme
 * @returns {Map<string, string>} category variable → colour
 */
function palette(theme) {
	const entries = toCSS(theme, { cssVariablePrefix: CODE_VAR_PREFIX })
		.split(';')
		.map((d) => d.split(':').map((s) => s.trim()))
		.filter(([name, value]) => name && value);
	return new Map(/** @type {[string, string][]} */ (entries));
}

const light = palette(pierreLight);
const dark = palette(pierreDark);

/**
 * A class per distinct light/dark colour pair, rather than a variable per
 * syntax category: there are ~130 categories and ~30 pairs, and
 * `class="t4"` is a third the length of `style="color:var(--code-punctuation-delimiter)"`
 * on every token of every block.
 *
 * Derived from the installed themes on both sides — here for the highlighter,
 * and into the checked-in `code-theme.css` — so the two agree as long as that
 * file is regenerated with the package, which `code-theme.test.js` enforces.
 */
const pairs = new Map(); // `${light}|${dark}` → class
/** @type {Map<string, string>} `var(--code-x)` → class */
export const TOKEN_CLASS = new Map();
for (const [name, color] of light) {
	if (name === `${CODE_VAR_PREFIX}foreground` || name === `${CODE_VAR_PREFIX}background`) continue;
	const key = `${color}|${dark.get(name) ?? color}`;
	if (!pairs.has(key)) pairs.set(key, `t${pairs.size}`);
	TOKEN_CLASS.set(`var(${name})`, pairs.get(key));
}

/**
 * The stylesheet: the foreground for both themes, then each pair's light colour
 * and its dark one under the `.dark` class app.html sets. Written out by
 * `npm run code-theme`.
 *
 * @returns {string}
 */
export function codeThemeCss() {
	const fg = `${CODE_VAR_PREFIX}foreground`;
	const rules = [...pairs].flatMap(([key, cls]) => {
		const [l, d] = key.split('|');
		return [
			`[data-code-figure] .${cls} {\n\tcolor: ${l};\n}`,
			`.dark [data-code-figure] .${cls} {\n\tcolor: ${d};\n}`
		];
	});
	return [
		'/* Generated by `npm run code-theme` from @pierre/highlights. Do not edit. */',
		'',
		`[data-code-figure] {\n\t${fg}: ${light.get(fg)};\n}`,
		'',
		`.dark [data-code-figure] {\n\t${fg}: ${dark.get(fg)};\n}`,
		'',
		...rules.flatMap((r) => [r, '']),
		''
	]
		.join('\n')
		.replace(/\n+$/, '\n');
}
